import type { Bundle, OutFile } from './types';

const quote = (text: string) => `'${text.replaceAll("'", `'\\''`)}'`;

function delimiterFor(content: string): string {
  const lines = new Set(content.split('\n'));
  let delimiter = 'INFRA_PICKER_EOF';
  while (lines.has(delimiter)) delimiter += '_';
  return delimiter;
}

function writeFile(file: OutFile): string {
  const delimiter = delimiterFor(file.content);
  const slash = file.path.lastIndexOf('/');
  const mkdir = slash > 0 ? `mkdir -p ${quote(file.path.slice(0, slash))}\n` : '';
  return `${mkdir}cat > ${quote(file.path)} <<'${delimiter}'\n${file.content}${delimiter}\n`;
}

export function buildScript(files: readonly OutFile[], steps: Bundle['steps']): string {
  const parts = [
    '#!/usr/bin/env bash',
    'set -euo pipefail',
    '',
    '# Generated by infra-picker. Read it before you run it.',
    '',
    ...files.map(writeFile),
  ];
  for (const step of steps) {
    parts.push(`# --- ${step.title} ---`, ...step.commands, '');
  }
  return parts.join('\n');
}
